"""
VICTOR Autostart Installer
Registers (or removes) tray mode in the current user's Startup folder so the
assistant is resident every time Windows logs in.

Uses a tiny generated .vbs launcher: it starts pythonw.exe with hidden window
state, so there is no console flash and no admin rights are required.

Usage:
    python scripts/install_autostart.py install
    python scripts/install_autostart.py uninstall
    python scripts/install_autostart.py status
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parents[1]
ENTRY_NAME = "VICTOR Tray.vbs"


def _startup_dir() -> Path:
    appdata = os.environ.get("APPDATA")
    if not appdata:
        raise RuntimeError("APPDATA is not set; cannot locate the Startup folder.")
    return Path(appdata) / "Microsoft" / "Windows" / "Start Menu" / "Programs" / "Startup"


def entry_path() -> Path:
    return _startup_dir() / ENTRY_NAME


def _pythonw() -> Path:
    candidate = ROOT_DIR / ".venv" / "Scripts" / "pythonw.exe"
    if candidate.exists():
        return candidate
    # Fall back to the interpreter's own folder (python.exe -> pythonw.exe)
    alt = Path(sys.executable).with_name("pythonw.exe")
    return alt if alt.exists() else Path(sys.executable)


def _launcher_script() -> str:
    pythonw = _pythonw()
    runner = ROOT_DIR / "run_victor.py"
    return (
        "' VICTOR AI assistant - tray autostart (generated by scripts/install_autostart.py)\n"
        "Set sh = CreateObject(\"WScript.Shell\")\n"
        f"sh.CurrentDirectory = \"{ROOT_DIR}\"\n"
        f"sh.Run \"\"\"{pythonw}\"\" \"\"{runner}\"\" --tray\", 0, False\n"
    )


def is_installed() -> bool:
    path = entry_path()
    if not path.exists():
        return False
    try:
        return str(ROOT_DIR) in path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return True


def install() -> Path:
    path = entry_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(_launcher_script(), encoding="utf-8")
    return path


def uninstall() -> Path:
    path = entry_path()
    try:
        if path.exists():
            path.unlink()
    except Exception:
        pass
    return path


def main(argv: list[str]) -> int:
    action = (argv[0] if argv else "status").lower()

    if action == "install":
        path = install()
        print(f"[+] Autostart installed: {path}")
        return 0
    if action == "uninstall":
        path = uninstall()
        print(f"[+] Autostart removed: {path}")
        return 0
    if action == "status":
        path = entry_path()
        print(f"[*] Startup entry: {path}")
        print(f"[*] Installed: {is_installed()}")
        print(f"[*] Interpreter: {_pythonw()}")
        return 0

    print(__doc__)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
